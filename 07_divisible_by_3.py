# Print numbers divisible by 3

numbers = [12, 7, 9, 20, 33, 42, 8, 15]

for i in numbers:
    if i % 3 == 0:
        print(i)



# Here I have a list of numbers. 
# I use a for loop to iterate each number, and the modulo operator checks whether the number is exactly divisible by 3, if not then skip it.